-- ----------------------------------------------------------------------------
-- 1. TABLES DEFINITION (MULTI-TENANT ARCHITECTURE)
-- ----------------------------------------------------------------------------

-- A. User Profiles (Directory & Account Metadata)
CREATE TABLE IF NOT EXISTS public.user_profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    full_name TEXT,
    email TEXT,
    admin_pin TEXT DEFAULT '1234',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- B. BNPL Accounts & Repayment Info
CREATE TABLE IF NOT EXISTS public.bnpl_accounts (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    provider TEXT NOT NULL,
    short_code CHAR(1) NOT NULL,
    brand_class TEXT NOT NULL,
    is_shariah BOOLEAN DEFAULT false,
    is_connected BOOLEAN DEFAULT false,
    outstanding_amount NUMERIC(10,2) DEFAULT 0.00,
    next_repayment_amount NUMERIC(10,2) DEFAULT 0.00,
    repayment_date DATE,
    repayment_status TEXT CHECK (repayment_status IN ('Unpaid', 'Upcoming', 'Paid')),
    CONSTRAINT bnpl_accounts_user_provider_unique UNIQUE (user_id, provider)
);

-- C. Monthly Budget Settings
CREATE TABLE IF NOT EXISTS public.user_budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid() UNIQUE,
    income NUMERIC(10,2) DEFAULT 5000.00,
    expenses NUMERIC(10,2) DEFAULT 3200.00
);

-- D. Payment History Log
CREATE TABLE IF NOT EXISTS public.payment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    account_id UUID REFERENCES public.bnpl_accounts(id) ON DELETE SET NULL,
    provider TEXT NOT NULL,
    amount_paid NUMERIC(10,2) NOT NULL,
    paid_at TIMESTAMPTZ DEFAULT NOW()
);

-- E. Refunds & Disputes
CREATE TABLE IF NOT EXISTS public.disputes (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    merchant TEXT NOT NULL,
    dispute_date DATE NOT NULL,
    amount NUMERIC(10,2) NOT NULL,
    status TEXT NOT NULL
);

