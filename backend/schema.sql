-- ----------------------------------------------------------------------------
-- 3. RPC STORED PROCEDURE: ATOMIC BNPL INSTALLMENT SETTLEMENT
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.settle_bnpl_installment(p_account_id UUID)
RETURNS JSON AS $$
DECLARE
    v_acc public.bnpl_accounts%ROWTYPE;
    v_paid NUMERIC;
    v_new_out NUMERIC;
BEGIN
    -- Lock row for atomic update
    SELECT * INTO v_acc
    FROM public.bnpl_accounts
    WHERE id = p_account_id AND user_id = auth.uid()
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Account not found or unauthorized';
    END IF;

    v_paid := COALESCE(v_acc.next_repayment_amount, 0);
    v_new_out := GREATEST(0, COALESCE(v_acc.outstanding_amount, 0) - v_paid);

    -- Update BNPL account status and balance
    UPDATE public.bnpl_accounts
    SET 
        repayment_status = 'Paid',
        outstanding_amount = v_new_out
    WHERE id = p_account_id;

    -- Record transaction in payment history
    INSERT INTO public.payment_history (user_id, account_id, provider, amount_paid)
    VALUES (auth.uid(), p_account_id, v_acc.provider, v_paid);

    RETURN json_build_object(
        'id', p_account_id,
        'paid_amount', v_paid,
        'new_outstanding', v_new_out,
        'provider', v_acc.provider
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

