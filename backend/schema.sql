-- 4. AUTOMATED AUTH TRIGGER: ONBOARDING & DEMO DATA SEEDER
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.seed_demo_data_on_signup()
RETURNS TRIGGER AS $$
BEGIN
    -- A. Create User Profile
    INSERT INTO public.user_profiles (id, full_name, email, admin_pin)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'admin_pin', '1234')
    )
    ON CONFLICT (id) DO NOTHING;

    -- B. Initialize Default Monthly Budget (RM 5,000 Income / RM 3,200 Expenses)
    INSERT INTO public.user_budget (user_id, income, expenses)
    VALUES (NEW.id, 5000.00, 3200.00)
    ON CONFLICT (user_id) DO NOTHING;

    -- C. Seed 5 Default BNPL Providers (Starting Disconnected for Clean Onboarding)
    INSERT INTO public.bnpl_accounts (
        user_id, provider, short_code, brand_class, outstanding_amount, 
        next_repayment_amount, repayment_date, repayment_status, is_shariah, is_connected
    ) VALUES
        (NEW.id, 'SPayLater', 'S', 'bg-[#ee4d2d] text-white', 450.00, 150.00, (CURRENT_DATE + INTERVAL '5 days')::DATE, 'Upcoming', true, false),
        (NEW.id, 'Atome', 'A', 'bg-[#facc15] text-slate-900', 360.00, 120.00, (CURRENT_DATE + INTERVAL '12 days')::DATE, 'Upcoming', true, false),
        (NEW.id, 'Grab PayLater', 'G', 'bg-[#00b14f] text-white', 200.00, 200.00, (CURRENT_DATE - INTERVAL '2 days')::DATE, 'Unpaid', true, false),
        (NEW.id, 'Touch ''n Go PayLater', 'T', 'bg-[#0062eb] text-white', 0.00, 0.00, (CURRENT_DATE + INTERVAL '18 days')::DATE, 'Paid', true, false),
        (NEW.id, 'hoolah', 'H', 'bg-[#ff3366] text-white', 180.00, 60.00, (CURRENT_DATE + INTERVAL '20 days')::DATE, 'Upcoming', false, false)
    ON CONFLICT (user_id, provider) DO NOTHING;

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    -- Fail-safe so user signup never gets blocked
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

